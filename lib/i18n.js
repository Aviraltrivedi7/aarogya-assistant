export function makeT(lang) {
  const source = lang === 'hi' ? hi : dict
  const fallback = dict
  return function t(key) {
    const val = key.split('.').reduce((o, k) => (o && o[k] !== undefined ? o[k] : undefined), source)
    if (val !== undefined) return val
    const fb = key.split('.').reduce((o, k) => (o && o[k] !== undefined ? o[k] : undefined), fallback)
    return fb !== undefined ? fb : key
  }
}
